def main():
    spec = json.loads(PROJECT.read_text(encoding='utf-8'))
    conn = next(c for c in spec['connections'] if c['id'] == CONN_ID)
    dev = next(d for d in conn['devices'] if d['id'] == DEVICE_ID)

    backup = PROJECT.with_suffix('.json.bak-solis-' + time.strftime('%Y%m%d'))
    shutil.copy2(PROJECT, backup)

    next_id = 400000
    points = []
    for addr, name, dt, note in POINTS:
        points.append({
            'id': next_id,
            'name': name,
            'area': 'input_register',
            'address': addr,
            'data_type': dt,
            'source': {'kind': 'static', 'value': 0.0},
            'note': note or None,
        })
        next_id += 1

    conn['name'] = '锦浪逆变器·COM7主机轮询'
    dev['name'] = '锦浪并网逆变器（从机1）'
    dev['points'] = points
    PROJECT.write_text(json.dumps(spec, ensure_ascii=False, indent=2), encoding='utf-8')

    # 槽位连续性检查：统计将形成的轮询分段
    slots = sorted((p['address'], 2 if p['data_type'] in ('u32', 'i32') else 1) for p in points)
    segs, start, end = [], slots[0][0], slots[0][0] + slots[0][1]
    for a, n in slots[1:]:
        if a <= end:
            end = max(end, a + n)
        else:
            segs.append((start, end))
            start, end = a, a + n
    segs.append((start, end))
    print(f'已写入 {len(points)} 个 FC04 点到「{conn["name"]}」/ 设备「{dev["name"]}」')
    print(f'备份: {backup.name}')
    print(f'轮询分段数: {len(segs)}（地址 0x{segs[0][0]:X} 起）')


if __name__ == '__main__':
    main()
